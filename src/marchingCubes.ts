// 256 x 16 triangle table (edge indices, -1 terminated).
const TRI_TABLE = buildTriTable();

class GrowableFloats {
  private data: Float32Array;
  private length = 0;

  constructor(initial = 4096) {
    this.data = new Float32Array(initial);
  }

  push3(a: number, b: number, c: number) {
    if (this.length + 3 > this.data.length) {
      const grown = new Float32Array(this.data.length * 2);
      grown.set(this.data);
      this.data = grown;
    }
    this.data[this.length++] = a;
    this.data[this.length++] = b;
    this.data[this.length++] = c;
  }

  toArray() {
    return this.data.slice(0, this.length);
  }
}

export interface MarchingCubesInput {
  values: Float32Array;
  grid: CubeGrid;
  isolevel: number;
}

/** Extracts an isosurface mesh (vertex soup with per-vertex gradient normals). */
export function marchingCubes({ values, grid, isolevel }: MarchingCubesInput): IsoGeometry {
  const { nx, ny, nz, origin, axes } = grid;
  const [ax, ay, az] = axes;
  const strideI = ny * nz;
  const strideJ = nz;
  const idx = (i: number, j: number, k: number) => i * strideI + j * strideJ + k;

  // Unit axis directions and spacings, for turning the index-space gradient
  // into a world-space normal (cube grids are effectively orthogonal).
  const hx = Math.hypot(ax[0], ax[1], ax[2]) || 1;
  const hy = Math.hypot(ay[0], ay[1], ay[2]) || 1;
  const hz = Math.hypot(az[0], az[1], az[2]) || 1;
  const ux: Vec3Tuple = [ax[0] / hx, ax[1] / hx, ax[2] / hx];
  const uy: Vec3Tuple = [ay[0] / hy, ay[1] / hy, ay[2] / hy];
  const uz: Vec3Tuple = [az[0] / hz, az[1] / hz, az[2] / hz];

  const cornerPos = (i: number, j: number, k: number): Vec3Tuple => [
    origin[0] + i * ax[0] + j * ay[0] + k * az[0],
    origin[1] + i * ax[1] + j * ay[1] + k * az[1],
    origin[2] + i * ax[2] + j * ay[2] + k * az[2],
  ];

  // Outward normal ∝ -∇f (density is highest inside the surface).
  const cornerNormal = (i: number, j: number, k: number): Vec3Tuple => {
    const i0 = i > 0 ? i - 1 : i;
    const i1 = i < nx - 1 ? i + 1 : i;
    const j0 = j > 0 ? j - 1 : j;
    const j1 = j < ny - 1 ? j + 1 : j;
    const k0 = k > 0 ? k - 1 : k;
    const k1 = k < nz - 1 ? k + 1 : k;
    const gi = (values[idx(i1, j, k)] - values[idx(i0, j, k)]) / ((i1 - i0) * hx || 1);
    const gj = (values[idx(i, j1, k)] - values[idx(i, j0, k)]) / ((j1 - j0) * hy || 1);
    const gk = (values[idx(i, j, k1)] - values[idx(i, j, k0)]) / ((k1 - k0) * hz || 1);
    return [
      -(gi * ux[0] + gj * uy[0] + gk * uz[0]),
      -(gi * ux[1] + gj * uy[1] + gk * uz[1]),
      -(gi * ux[2] + gj * uy[2] + gk * uz[2]),
    ];
  };

  const positions = new GrowableFloats();
  const normals = new GrowableFloats();

  const cornerValue = new Float64Array(8);
  const cornerXYZ: Vec3Tuple[] = Array.from({ length: 8 }, () => [0, 0, 0]);
  const cornerN: Vec3Tuple[] = Array.from({ length: 8 }, () => [0, 0, 0]);
  const edgeP: Vec3Tuple[] = Array.from({ length: 12 }, () => [0, 0, 0]);
  const edgeN: Vec3Tuple[] = Array.from({ length: 12 }, () => [0, 0, 0]);

  for (let i = 0; i < nx - 1; i++) {
    for (let j = 0; j < ny - 1; j++) {
      for (let k = 0; k < nz - 1; k++) {
        let cubeIndex = 0;
        for (let c = 0; c < 8; c++) {
          const [dx, dy, dz] = CORNER_OFFSETS[c];
          const v = values[idx(i + dx, j + dy, k + dz)];
          cornerValue[c] = v;
          if (v < isolevel) cubeIndex |= 1 << c;
        }

        const edges = EDGE_TABLE[cubeIndex];
        if (edges === 0) continue;

        // Only compute corner geometry for this cell when it produces triangles.
        for (let c = 0; c < 8; c++) {
          const [dx, dy, dz] = CORNER_OFFSETS[c];
          cornerXYZ[c] = cornerPos(i + dx, j + dy, k + dz);
          cornerN[c] = cornerNormal(i + dx, j + dy, k + dz);
        }

        for (let e = 0; e < 12; e++) {
          if ((edges & (1 << e)) === 0) continue;
          const [a, b] = EDGE_CORNERS[e];
          const va = cornerValue[a];
          const vb = cornerValue[b];
          let t = (isolevel - va) / (vb - va);
          if (!Number.isFinite(t)) t = 0.5;
          const pa = cornerXYZ[a];
          const pb = cornerXYZ[b];
          const na = cornerN[a];
          const nb = cornerN[b];
          edgeP[e][0] = pa[0] + t * (pb[0] - pa[0]);
          edgeP[e][1] = pa[1] + t * (pb[1] - pa[1]);
          edgeP[e][2] = pa[2] + t * (pb[2] - pa[2]);
          edgeN[e][0] = na[0] + t * (nb[0] - na[0]);
          edgeN[e][1] = na[1] + t * (nb[1] - na[1]);
          edgeN[e][2] = na[2] + t * (nb[2] - na[2]);
        }

        const tris = TRI_TABLE[cubeIndex];
        for (let n = 0; tris[n] !== -1; n += 3) {
          for (let m = 0; m < 3; m++) {
            const e = tris[n + m];
            const p = edgeP[e];
            const nrm = edgeN[e];
            const len = Math.hypot(nrm[0], nrm[1], nrm[2]) || 1;
            positions.push3(p[0], p[1], p[2]);
            normals.push3(nrm[0] / len, nrm[1] / len, nrm[2] / len);
          }
        }
      }
    }
  }

  return { positions: positions.toArray(), normals: normals.toArray() };
}

